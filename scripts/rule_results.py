"""Write docs/rule_results.md from the evaluation marts. Every number comes from here:
    python scripts/rule_results.py     (needs `make build`)"""
from pathlib import Path

import duckdb

ROOT = Path(__file__).resolve().parent.parent
con = duckdb.connect(str(ROOT / "data" / "aml.duckdb"), read_only=True)


def md(sql: str, fmt: dict[str, str]) -> str:
    cur = con.execute(sql)
    cols = [d[0] for d in cur.description]
    rows = cur.fetchall()

    def f(c, v):
        if v is None:
            return "n/a"
        return format(v, fmt.get(c, "")) if c in fmt else str(v)

    return "\n".join(["| " + " | ".join(cols) + " |", "|" + "---|" * len(cols)]
                     + ["| " + " | ".join(f(c, v) for c, v in zip(cols, r)) + " |" for r in rows])


perf = md("""select rule_id, split, n_population as accounts, n_labelled_accounts as labelled,
    n_alerted_accounts as alerted, tp_accounts as tp, precision, account_recall as recall,
    alerts_per_1000_accounts as per_1000, txn_recall, precision_at_100 as p_at_100
    from marts.fct_rule_performance
    where rule_id not like 'rule_dummy%'
    order by rule_id, case split when 'all' then 0 when 'tune' then 1 else 2 end""",
          {"precision": ".4f", "recall": ".4f", "per_1000": ".2f", "txn_recall": ".4f", "p_at_100": ".2f"})
base = md("""select split, n_population as accounts, n_labelled_accounts as labelled,
    round(n_labelled_accounts::double / n_population, 4) as base_rate
    from marts.fct_rule_performance where rule_id = 'rule_dummy_all'
    order by case split when 'all' then 0 when 'tune' then 1 else 2 end""", {})
pat = md("""select pattern_type, rule_id, round(txn_recall, 3) as recall
    from marts.fct_rule_pattern_recall where split = 'all' and rule_id not like 'rule_dummy%'
    order by pattern_type, rule_id""", {})
ov = md("""select rule_a, rule_b, n_alerted_a, n_alerted_b, n_both, n_both_labelled, round(jaccard, 4) as jaccard
    from marts.fct_rule_overlap where rule_a not like 'rule_dummy%' and rule_b not like 'rule_dummy%'
    order by n_both desc""", {})
Path(ROOT / "docs" / "rule_results.md").write_text(f"""# Rule results (HI-Small)

Generated by `python scripts/rule_results.py`; do not edit by hand. Unit: account. Splits: tune =
days 1-7, validate = days 8-18 (`tune_last_day` in `dbt_project.yml`). Labels are per split.
Parameter values were selected on tune-split metrics only (criterion: highest recall with <= 10
alerts per 1,000 accounts; grid script read only the tune split). Disclosure: `make eval` prints
all splits, so validate was seen at each rule's untuned spec defaults before tuning, and that view
prompted one design change (alert once per account per day instead of only the first time, after
validate showed almost no structuring alerts). Validate is therefore not a perfectly untouched
holdout; the LI-Small run (never tuned on) is the clean out-of-sample check.
`precision` is compared with the base rate below, not with 50%.

## Base rate (labelled share of the population)

{base}

## Performance per rule

{perf}

## Transaction-level recall by pattern type (whole window)

{pat}

## Overlap between rules (whole window, distinct alerted accounts)

{ov}
""")
print("wrote docs/rule_results.md")
